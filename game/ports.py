"""규칙과 영속 구현 사이의 경계. 구현체는 동일 트랜잭션을 공유한다."""
from collections.abc import Callable
from typing import Protocol, TypeVar

from game.schemas import Character, GameStateOut, PurchaseResult


T = TypeVar("T")


class CharacterStore(Protocol):
    def get_by_user(self, user_id: str) -> Character | None: ...
    def create(self, user_id: str, name: str) -> Character: ...
    def update_name(self, character_id: str, name: str) -> Character: ...
    def get_state(self, character_id: str) -> GameStateOut: ...
    def save_state(self, state: GameStateOut) -> None: ...
    def lock(self, character_id: str) -> None: ...


class CoinLedger(Protocol):
    def get_balance(self, character_id: str) -> int: ...
    def has_first_pass(self, character_id: str, stage: int, concept_id: str) -> bool: ...
    def append(self, character_id: str, amount: int, reason: str, key: str) -> None: ...


class UnitOfWork(Protocol):
    def run(self, work: Callable[[], T]) -> T: ...


class PurchaseStore(Protocol):
    def find_result(self, character_id: str, key: str) -> PurchaseResult | None: ...
    def save_result(self, character_id: str, key: str, result: PurchaseResult) -> None: ...
